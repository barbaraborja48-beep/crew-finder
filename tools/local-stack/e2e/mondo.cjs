// Mondo Disko screens, for comparing the live version with the new one pixel by pixel.
const { phone, startCrew, shot, done } = require('./lib.cjs')
;(async () => {
  const B = await phone('Barbara', '2026-10-25T01:30:00+02:00')
  await B.addStyleTag({ content: '*{animation:none!important;transition:none!important;caret-color:transparent!important}' }).catch(() => {})
  await B.context().addInitScript(() => document.addEventListener('DOMContentLoaded', () => {
    const s = document.createElement('style'); s.textContent = '*{animation:none!important;transition:none!important;caret-color:transparent!important}'; document.head.appendChild(s)
  }))
  const code = await startCrew(B, 'mondo', 'Mondo Disko')
  await B.getByPlaceholder('What your crew calls you').fill('Barbara')
  await B.getByRole('button', { name: 'Join crew' }).click()
  await B.locator('nav.tabbar').waitFor()
  await B.clock.pauseAt(new Date('2026-10-25T01:31:00+02:00'))
  await shot(B, 'm1-map', { wait: 1500 })
  await B.getByRole('button', { name: 'Pin', exact: true }).click()
  await shot(B, 'm2-pin-page', { wait: 1000 })
  await B.locator('button.dj').click()
  await shot(B, 'm3-lineup', { wait: 1000 })
  await B.getByRole('button', { name: 'Close' }).click()
  await B.locator('nav.tabbar button', { hasText: 'Map' }).click()
  await B.getByRole('button', { name: 'P2' }).click().catch(() => B.getByRole('button', { name: 'Planta 2' }).click())
  await shot(B, 'm4-map-p2', { wait: 1000 })
  await done()
})().catch(e => { console.error(e); process.exit(1) })
