// Preview for the 27 Oct round: welcome copy, tidy festival map, adjustable list, clearer suggestions, colours.
const { sql, phone, join, refresh, shot, check, done, APP } = require('./lib.cjs')
const IPHONE = { width: 402, height: 874 }
const T = '2026-10-31T20:40:00+01:00'
const tab = (p, name) => p.locator('nav.tabbar button', { hasText: name }).click()
const mapHeight = p => p.evaluate(() => [...document.querySelectorAll('.screen > div')].find(d => d.style.transform === '' && d.querySelector('[style*="scale("]') && d.offsetHeight > 100)?.offsetHeight ?? 0)

;(async () => {
  const B = await phone('Barbara', T, { viewport: IPHONE })
  await B.goto(APP)
  await shot(B, 'r01-welcome', { wait: 800 })
  await B.getByRole('button', { name: 'Start a crew' }).click().catch(() => {})
  await B.getByPlaceholder('Crew name, e.g. Saturday squad').fill('Bruja squad')
  await B.getByRole('button', { name: 'Create crew' }).click()
  await B.getByPlaceholder('What your crew calls you').fill('Barbara')
  await B.getByRole('button', { name: 'Join crew' }).click()
  await B.locator('nav.tabbar').waitFor()
  const L = await phone('Lara', T, { viewport: IPHONE })
  const M = await phone('Mar', T, { viewport: IPHONE })
  await join(L, 'bruja-squad', 'Lara')
  await join(M, 'bruja-squad', 'Mar')
  await sql(`update members set color = case name when 'Barbara' then '#d23bff' when 'Lara' then '#b6ff3b' else '#ffc83b' end, acc = case name when 'Barbara' then 11 when 'Lara' then 10 else 15 end`)
  for (const [p, stage, x] of [[B, 'elrow', 200], [L, 'Brunch!', 150], [M, 'The Jail', 250]]) {
    await refresh(p)
    await tab(p, 'Pin')
    await p.getByRole('button', { name: new RegExp(`^${stage}`) }).first().click()
    await p.mouse.click(x, 560)
    await p.waitForTimeout(800)
  }
  await refresh(B)
  await tab(B, 'Map')
  await shot(B, 'r02-map-tidy', { wait: 1000 })
  check(!(await B.locator('body').innerText()).includes('Sitemap'), 'no legend text in the page')

  // Barbara guesses where Mar went: the suggestion shows on the map and in the list
  await tab(B, 'Crew')
  await B.getByRole('button', { name: /^Mar/ }).first().click()
  await B.getByRole('button', { name: 'Buddy up' }).click()
  await B.getByRole('button', { name: 'Close' }).click()
  await refresh(M)
  await tab(M, 'Crew')
  await M.getByRole('button', { name: 'Buddy up', exact: true }).click()
  await M.waitForTimeout(1200)
  await refresh(B)
  await tab(B, 'Crew')
  await B.getByRole('button', { name: /^Mar/ }).first().click()
  await B.getByRole('button', { name: 'Let go' }).click()
  await B.getByRole('button', { name: /^Bar$/ }).click()
  await B.getByRole('button', { name: 'Let go' }).last().click()
  await B.waitForTimeout(1200)
  await B.getByRole('button', { name: 'Close' }).first().click()
  await tab(B, 'Map')
  await shot(B, 'r03-map-suggestion', { wait: 900 })
  check(await B.getByText(/Probably at Bar/).first().isVisible(), 'list shows “Probably at …” for Mar')
  await tab(B, 'Crew')
  await shot(B, 'r04-crew-hint-note', { wait: 600 })
  check(await B.getByText('PinGü stores data for improvement purposes only.').isVisible(), 'Crew tab note says what is kept')

  // Drag the list handle up (smaller map, still whole) and down (map at its full size)
  await tab(B, 'Map')
  const handle = B.getByRole('separator', { name: /resize/ })
  const hb = await handle.boundingBox()
  const before = await B.locator('.screen').first().evaluate(el => el.querySelector('nav') ? 0 : 0)
  await B.mouse.move(hb.x + hb.width / 2, hb.y + hb.height / 2)
  await B.mouse.down()
  await B.mouse.move(hb.x + hb.width / 2, hb.y - 140, { steps: 8 })
  await B.mouse.up()
  await shot(B, 'r05-map-list-up', { wait: 500 })
  // slide the map down with a finger to see the top of the venue
  const fr = await B.locator('[style*="touch-action: none"]').first().boundingBox()
  await B.mouse.move(fr.x + 120, fr.y + 60)
  await B.mouse.down()
  await B.mouse.move(fr.x + 120, fr.y + 220, { steps: 8 })
  await B.mouse.up()
  await shot(B, 'r05b-map-slid', { wait: 400 })
  const hb2 = await handle.boundingBox()
  check(hb2.y < hb.y - 100, `list handle moved up (${Math.round(hb.y)} → ${Math.round(hb2.y)})`)
  await B.reload()
  await B.locator('nav.tabbar').waitFor()
  await B.waitForTimeout(800)
  const hb3 = await B.getByRole('separator', { name: /resize/ }).boundingBox()
  check(Math.abs(hb3.y - hb2.y) < 4, 'the list height is remembered after reopening')
  await B.mouse.move(hb3.x + hb3.width / 2, hb3.y + 5)
  await B.mouse.down()
  await B.mouse.move(hb3.x + hb3.width / 2, hb3.y + 400, { steps: 8 })
  await B.mouse.up()
  await shot(B, 'r06-map-list-down', { wait: 500 })

  // Colours and the wheel
  await B.getByRole('button', { name: 'Your profile' }).click()
  await shot(B, 'r07-colors', { wait: 600 })
  check(await B.getByText('Select your PinGü color').isVisible(), 'new color label')
  check(await B.getByLabel('Pick your own color').isVisible(), 'color wheel is there')
  await B.locator('input[type=color]').evaluate(el => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, '#101040'); el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })) })
  await B.waitForTimeout(1500)
  const c = (await sql(`select color from members where name = 'Barbara'`))[0].color
  console.log('   custom color saved as', c)
  check(c !== '#d23bff', 'a picked color is saved (very dark ones lifted)')
  await shot(B, 'r08-colors-custom', { wait: 400 })
  await done()
})().catch(async e => { console.error(e); try { const ps = require('./lib.cjs'); } catch {} ; process.exit(1) })
