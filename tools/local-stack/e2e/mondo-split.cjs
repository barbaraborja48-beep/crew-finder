// Mondo: pull the list up, then tap the club plan. The pin must land where the finger was.
const { sql, phone, startCrew, shot, check, done } = require('./lib.cjs')
;(async () => {
  const B = await phone('Barbara', '2026-10-25T01:30:00+02:00', { viewport: { width: 402, height: 874 } })
  await startCrew(B, 'mondo', 'Mondo')
  await B.getByPlaceholder('What your crew calls you').fill('Barbara')
  await B.getByRole('button', { name: 'Join crew' }).click()
  await B.locator('nav.tabbar').waitFor()
  await B.getByRole('dialog', { name: 'Welcome to PinGü' }).getByRole('button', { name: 'Skip' }).click().catch(() => {})
  const h = B.getByRole('separator', { name: /resize/ })
  const hb = await h.boundingBox()
  await B.mouse.move(hb.x + hb.width / 2, hb.y + 5); await B.mouse.down()
  await B.mouse.move(hb.x + hb.width / 2, hb.y - 260, { steps: 8 }); await B.mouse.up()
  await B.waitForTimeout(400)
  // tap the toilet icon's spot on the plan (whatever is visible right above it)
  const wc = B.locator('button[aria-label*="WC"], button[aria-label*="Toilet"], button[aria-label*="toilet"]').first()
  const box = await wc.boundingBox().catch(() => null)
  console.log('   WC icon', box && { x: Math.round(box.x), y: Math.round(box.y) })
  await shot(B, 'm5-split-up', { wait: 300 })
  const fr = await B.locator('[style*="touch-action: none"]').first().boundingBox()
  const tap = { x: fr.x + 190, y: fr.y + 120 }
  await B.mouse.click(tap.x, tap.y)
  await B.waitForTimeout(1500)
  const you = await B.getByText('You', { exact: true }).first().boundingBox()
  console.log('   tapped', tap, '→ penguin label at', you && { x: Math.round(you.x + you.width / 2), y: Math.round(you.y) })
  check(you && Math.abs(you.x + you.width / 2 - tap.x) < 6 && Math.abs(you.y - tap.y) < 20, 'tap pins right under the finger with the list pulled up')
  await shot(B, 'm6-split-pinned', { wait: 500 })
  await done()
})().catch(e => { console.error(e); process.exit(1) })
